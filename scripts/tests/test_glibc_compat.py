"""The glibc floor's two pieces, offline: scripts/glibc-compat.py turns an `objdump -T`
listing into the pins the floor needs (and leaves out what has no older version), the committed
scripts/glibc-compat.h is what it writes for the listing it names, and scripts/host-glibc.sh's
host_glibc_check passes a program within the floor and names the one past it (objdump is a
made-up one on PATH). No compiler, no Frame.

  python3 scripts/tests/test_glibc_compat.py
"""
import os
import re
import subprocess
import sys
import tempfile
import unittest

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, "scripts"))
import importlib  # noqa: E402

compat = importlib.import_module("glibc-compat")

# objdump -T lines: a default version (GLIBC_2.43), an older one kept for old binaries
# ((GLIBC_2.17)), a symbol new in 2.40 with no older version, an old symbol, a version node.
LISTING = """
libm.so.6:     file format elf64-littleaarch64
DYNAMIC SYMBOL TABLE:
0000000000050c30 g    DF .text	0000000000000204  GLIBC_2.43  asinf
0000000000014ba0 g    DF .text	0000000000000050 (GLIBC_2.17) asinf
0000000000041000 g    DF .text	0000000000000100  GLIBC_2.40  exp2m1f
0000000000012000 g    DF .text	0000000000000040  GLIBC_2.17  cosf
0000000000000000 g    DO *ABS*	0000000000000000  GLIBC_2.43  GLIBC_2.43
0000000000070000 g    DF .text	0000000000000080  GLIBC_2.40  _ZGVnN4v_tanhf
0000000000020000 g    DF .text	0000000000000060  GLIBC_2.42  cfsetospeed
0000000000020100 g    DF .text	0000000000000060 (GLIBC_2.17) cfsetospeed
"""


class Generator(unittest.TestCase):
    def test_pins_only_what_has_an_older_version_within_the_floor(self):
        pinned, unpinnable = compat.pins(LISTING, (2, 39))
        self.assertEqual(pinned, [("asinf", (2, 17)), ("cfsetospeed", (2, 17))])
        self.assertEqual(unpinnable, [("exp2m1f", (2, 40))])   # the vector variant never counts

    def test_a_floor_at_the_listings_glibc_pins_nothing(self):
        pinned, unpinnable = compat.pins(LISTING, (2, 43))
        self.assertEqual((pinned, unpinnable), ([], []))

    def test_the_header_binds_each_pin_and_turns_fast_math_off(self):
        text = compat.render(*compat.pins(LISTING, (2, 39)), (2, 39), "a test listing")
        self.assertIn('__asm__(".symver asinf,asinf@GLIBC_2.17");', text)
        self.assertIn("#undef __FAST_MATH__", text)
        self.assertIn("exp2m1f (2.40)", text)
        self.assertNotRegex(text, r"(?m)^\s*#\s*include")   # nothing before the source's own feature macros

    def test_the_committed_header_is_the_generators(self):
        """It was generated: regenerating it from a saved listing gives the same pins."""
        header = open(os.path.join(REPO, "scripts", "glibc-compat.h")).read()
        pins = re.findall(r'^__asm__\("\.symver (\w+),\1@(GLIBC_[\d.]+)"\);$', header, re.M)
        self.assertGreater(len(pins), 20)
        self.assertIn(("sqrtf", "GLIBC_2.17"), pins)
        self.assertIn(("remainder", "GLIBC_2.17"), pins)
        floor = compat.floor()
        for name, version in pins:
            self.assertLessEqual(tuple(int(x) for x in version[6:].split(".")), floor, name)
        self.assertRegex(header.splitlines()[0], r"^/\* Generated by scripts/glibc-compat\.py from glibc 2\.\d+ ")


class Check(unittest.TestCase):
    """host_glibc_check, with objdump a script that prints a listing per file name."""

    def run_check(self, listings):
        with tempfile.TemporaryDirectory() as d:
            for name, text in listings.items():
                with open(os.path.join(d, name), "w") as f:
                    f.write(text)
            objdump = os.path.join(d, "objdump")
            with open(objdump, "w") as f:
                f.write('#!/bin/sh\ncat "$2"\n')
            os.chmod(objdump, 0o755)
            env = dict(os.environ, PATH=d + ":" + os.environ["PATH"])
            files = " ".join(os.path.join(d, n) for n in listings)
            r = subprocess.run(["bash", "-c", f'. "$1"; host_glibc_check {files}', "x",
                                os.path.join(REPO, "scripts", "host-glibc.sh")], env=env, capture_output=True, text=True)
            return r.returncode, r.stderr.strip()

    def test_within_the_floor_passes(self):
        code, err = self.run_check({"ok": "x (GLIBC_2.17) f\ny (GLIBC_2.38) g\nz GLIBCXX_3.4.30 h\nw CXXABI_1.3.9 i\n"})
        self.assertEqual((code, err), (0, ""))

    def test_past_the_floor_fails_and_names_the_file_and_version(self):
        code, err = self.run_check({"ok": "x (GLIBC_2.17) f\n", "bad": "x (GLIBC_2.17) f\ny (GLIBC_2.43) sqrtf\n"})
        self.assertEqual(code, 1)
        self.assertIn("bad needs GLIBC_2.43", err)

    def test_a_newer_libstdcxx_fails_too(self):
        code, err = self.run_check({"cxx": "x GLIBCXX_3.4.34 f\n"})
        self.assertEqual(code, 1)
        self.assertIn("GLIBCXX_3.4.34", err)


if __name__ == "__main__":
    unittest.main()
